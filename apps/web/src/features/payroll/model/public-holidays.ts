const LABOR_DAY = '05-01';

/** 관공서 공휴일. 5인 이상 사업장의 유급휴일 (근기법 §55②) */
export const isPublicHoliday = (localDate: string) => PUBLIC_HOLIDAYS.has(localDate);

/** 노동절(5/1). 사업장 규모와 상관없이 유급휴일 (노동절 제정에 관한 법률) */
export const isLaborDay = (localDate: string) => localDate.slice(5) === LABOR_DAY;

/** 그날 유급휴일인가. 공휴일은 5인 이상 신고일만, 노동절은 늘 */
export const isPaidHoliday = (localDate: string, fiveOrMore: boolean) =>
  isLaborDay(localDate) || (fiveOrMore && isPublicHoliday(localDate));
